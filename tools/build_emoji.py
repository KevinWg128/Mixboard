#!/usr/bin/env python3
"""Builds app/src/main/java/hk/mixboard/ime/EmojiData.kt from Unicode's emoji-test.txt.

    python3 tools/build_emoji.py [path/to/emoji-test.txt]

Without a path it downloads emoji-test.txt into tools/cache/ first.
Keeps fully-qualified emoji up to MAX_EMOJI_VERSION, grouped as Unicode groups them,
and leaves out skin-tone and hair variants (the base emoji stays).
"""
import pathlib
import sys
import urllib.request

VERSION = "15.1"
URL = f"https://unicode.org/Public/emoji/{VERSION}/emoji-test.txt"
MAX_EMOJI_VERSION = 15.0  # phones from 2023 on show all of these

ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / "tools" / "cache" / f"emoji-test-{VERSION}.txt"
OUT = ROOT / "app/src/main/java/hk/mixboard/ime/EmojiData.kt"

GROUPS = [
    ("Smileys & Emotion", "😀"),
    ("People & Body", "👋"),
    ("Animals & Nature", "🐻"),
    ("Food & Drink", "🍔"),
    ("Travel & Places", "🚗"),
    ("Activities", "⚽"),
    ("Objects", "💡"),
    ("Symbols", "🔣"),
    ("Flags", "🏁"),
]
SKIP = set(range(0x1F3FB, 0x1F400)) | set(range(0x1F9B0, 0x1F9B4))  # skin tones, hair


def load(path):
    if path:
        return pathlib.Path(path).read_text(encoding="utf-8")
    if not CACHE.exists():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        print("downloading", URL)
        with urllib.request.urlopen(URL) as r:
            CACHE.write_bytes(r.read())
    return CACHE.read_text(encoding="utf-8")


def parse(text):
    groups = {}
    group = None
    for line in text.splitlines():
        if line.startswith("# group: "):
            group = line[len("# group: "):].strip()
            continue
        if not line or line.startswith("#"):
            continue
        codes, rest = line.split(";", 1)
        status, comment = rest.split("#", 1)
        if status.strip() != "fully-qualified":
            continue
        if any(int(c, 16) in SKIP for c in codes.split()):
            continue
        emoji, version, _name = comment.strip().split(" ", 2)
        if float(version[1:]) > MAX_EMOJI_VERSION:
            continue
        groups.setdefault(group, []).append(emoji)
    return groups


def kotlin(groups):
    out = [
        "package hk.mixboard.ime",
        "",
        "/**",
        " * Emoji by Unicode group, from emoji-test.txt (fully-qualified, no skin-tone or hair variants).",
        " * Generated by tools/build_emoji.py; do not edit by hand.",
        " */",
        "class EmojiCategory(val icon: String, val emoji: List<String>)",
        "",
        "object EmojiData {",
        "    val CATEGORIES: List<EmojiCategory> = listOf(",
    ]
    for name, icon in GROUPS:
        items = groups[name]
        text = "\n".join(" ".join(items[i:i + 16]) for i in range(0, len(items), 16))
        # One JVM string constant must stay under 65535 bytes of modified UTF-8.
        assert len(text.encode("utf-16-le")) // 2 * 3 < 60000, name
        out.append(f"        // {name}: {len(items)}")
        out.append(f'        EmojiCategory("{icon}", emoji(')
        out.append('            """')
        out.extend("            " + line for line in text.split("\n"))
        out.append('            """')
        out.append("        )),")
    out += [
        "    )",
        "",
        "    private fun emoji(s: String): List<String> = s.split(' ', '\\n').filter { it.isNotEmpty() }",
        "}",
        "",
    ]
    return "\n".join(out)


def main():
    groups = parse(load(sys.argv[1] if len(sys.argv) > 1 else None))
    missing = [name for name, _ in GROUPS if name not in groups]
    if missing:
        sys.exit(f"groups not found in emoji-test.txt: {missing}")
    OUT.write_text(kotlin(groups), encoding="utf-8")
    for name, _ in GROUPS:
        print(f"{len(groups[name]):5d}  {name}")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
